<h2>3. Unusual or Persistent Fatigue</h2>

<p>Everyone feels tired sometimes. However, unexplained fatigue that is new, persistent, or much stronger than usual can deserve attention, especially when it occurs with breathlessness, dizziness, chest discomfort, or reduced ability to perform normal activities.</p>

<p>Fatigue can occur when the heart is not pumping blood effectively, but it is also associated with many other conditions. This makes the pattern and combination of symptoms important.</p>

<p>Women may experience unusual tiredness or weakness as part of a heart attack, sometimes alongside symptoms such as shortness of breath, nausea, or back or jaw discomfort. This is one reason heart symptoms should not be judged only by the presence or absence of severe chest pain.</p>

