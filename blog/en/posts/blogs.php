<h2>2. Shortness of Breath During Routine Activities</h2>

<p>Getting out of breath after intense exercise can be normal. New breathlessness during activities that were previously comfortable is different and should not automatically be blamed on age, lack of fitness, or stress.</p>

<p>Heart conditions can affect how efficiently blood and oxygen are delivered around the body. Breathlessness may occur with coronary artery disease, heart failure, heart valve problems, or certain abnormal heart rhythms.</p>

