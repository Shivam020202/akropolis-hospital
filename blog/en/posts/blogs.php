<h2>5. Dizziness, Lightheadedness, or Fainting</h2>

<p>Occasional dizziness can have many causes, including dehydration, low blood pressure, medication effects, or standing up suddenly. But repeated dizziness, unexplained lightheadedness, or fainting can sometimes be associated with an abnormal heart rhythm or reduced blood flow.</p>

<p>Fainting is especially important when it occurs during physical activity or together with chest discomfort, palpitations, or breathlessness. These combinations require prompt medical assessment.</p>

<p>Do not try to diagnose the cause yourself. A healthcare professional may need to check your blood pressure, heart rhythm, medical history, and other possible causes.</p>

<h2>6. Swelling in the Feet, Ankles, or Legs</h2>

