<p>Palpitations are the sensation of feeling your heartbeat. You may notice pounding, racing, fluttering, skipped beats, or an irregular rhythm in your chest.</p>

<p>Palpitations can occur because of stress, caffeine, certain medicines, hormonal changes, or other non-cardiac causes. They can also occur with an arrhythmia, which is an abnormal heart rhythm.</p>

